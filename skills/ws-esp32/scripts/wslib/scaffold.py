"""Generate board_pins.h and starter projects (ESP-IDF, Arduino, PlatformIO)."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any, Dict, List, Optional

from .data import TEMPLATES_DIR
from .display import display_dependencies, render_display

FRAMEWORKS = ("idf", "arduino", "pio")
PIO_PLATFORM = ("https://github.com/pioarduino/platform-espressif32/releases/download/"
                "stable/platform-espressif32.zip")


def _macro(*parts: str) -> str:
    return "WS_" + "_".join(re.sub(r"[^A-Za-z0-9]", "_", p).upper() for p in parts)


def render_header(board: Dict[str, Any]) -> str:
    ver = board["verification"]
    lines: List[str] = [
        "/*",
        f" * board_pins.h for {board['name']}",
        f" * Generated by the ws-esp32 skill from data/boards/{board['id']}.json.",
        f" * Verification: {ver['status']} (checked {ver.get('checked', '?')})",
    ]
    lines += [f" * Source: {s}" for s in ver.get("sources", [])]
    lines += [" * Regenerate this file instead of editing it by hand.", " */", "#pragma once", ""]
    lines += [
        f'#define WS_BOARD_ID "{board["id"]}"',
        f'#define WS_BOARD_NAME "{board["name"]}"',
        f'#define WS_BOARD_SOC "{board["soc"]}"',
        f"#define WS_FLASH_MB {board['flash_mb']}",
        f"#define WS_PSRAM_MB {board['psram_mb']}",
    ]
    for p in board["peripherals"]:
        desc = p.get("part") or p.get("protocol") or p["kind"]
        extra = f" over {p['bus']}" if p.get("bus") else ""
        lines += ["", f"/* {p['id']}: {desc}{extra} */"]
        res = p.get("resolution")
        if res:
            lines.append(f"#define {_macro(p['id'], 'H_RES')} {res[0]}")
            lines.append(f"#define {_macro(p['id'], 'V_RES')} {res[1]}")
        if p.get("addr"):
            note = "  /* typical, not verified */" if p.get("addr_verified") is False else ""
            lines.append(f"#define {_macro(p['id'], 'I2C_ADDR')} {p['addr']}{note}")
        for sig, val in (p.get("pins") or {}).items():
            name = _macro(p["id"], sig)
            if val is None:
                lines.append(f"/* {name}: unknown, check the schematic */")
            elif isinstance(val, str):
                lines.append(f"#define {name}_EXIO {val[4:]}  /* on the IO expander, not a GPIO */")
            else:
                lines.append(f"#define {name} {val}")
    lines.append("")
    return "\n".join(lines)


def arduino_fqbn(board: Dict[str, Any], chip: Dict[str, Any]) -> str:
    opts = [f"FlashSize={board['flash_mb']}M"]
    if board["chip"] in ("esp32s3", "esp32"):
        opts.append({"octal": "PSRAM=opi", "quad": "PSRAM=enabled"}.get(board["psram_mode"],
                                                                          "PSRAM=disabled"))
    if board["usb"].get("console") == "usb_serial_jtag":
        opts.append("CDCOnBoot=cdc")
    return f"esp32:esp32:{chip['arduino_board']}:" + ",".join(opts)


def sdkconfig_defaults(board: Dict[str, Any], chip: Dict[str, Any]) -> str:
    lines = [
        f"# Generated for {board['name']}",
        f'CONFIG_IDF_TARGET="{chip["idf_target"]}"',
        f"CONFIG_ESPTOOLPY_FLASHSIZE_{board['flash_mb']}MB=y",
        "CONFIG_PARTITION_TABLE_SINGLE_APP_LARGE=y",
        "CONFIG_FREERTOS_HZ=1000",
    ]
    if board["psram_mode"] != "none":
        lines += ["CONFIG_SPIRAM=y",
                  "CONFIG_SPIRAM_MODE_OCT=y" if board["psram_mode"] == "octal" else "CONFIG_SPIRAM_MODE_QUAD=y",
                  "CONFIG_SPIRAM_SPEED_80M=y"]
    if board["usb"].get("console") == "usb_serial_jtag":
        lines.append("CONFIG_ESP_CONSOLE_USB_SERIAL_JTAG=y")
    return "\n".join(lines) + "\n"


def idf_component_yml(board: Dict[str, Any], active: Optional[Dict[str, str]] = None) -> str:
    active = active or {}
    lines = ["dependencies:", '  idf: ">=5.2"' if active else '  idf: ">=5.1"']
    for comp, ver in active.items():
        lines.append(f'  {comp}: "{ver}"')
    lines += ["  # Drivers for this board's peripherals. Uncomment as you use them,",
              "  # and pin versions (e.g. \"^1.0\") before releasing."]
    seen = set(active)
    for p in board["peripherals"]:
        for comp in p.get("idf_components", []):
            if comp not in seen:
                seen.add(comp)
                lines.append(f'  # {comp}: "*"   # {p["id"]} ({p.get("part", "")})')
    return "\n".join(lines) + "\n"


def platformio_ini(board: Dict[str, Any], chip: Dict[str, Any], name: str) -> str:
    flags = ["-DCORE_DEBUG_LEVEL=3"]
    lines = [
        "; Generated by the ws-esp32 skill.",
        "; pioarduino provides Arduino-ESP32 3.x (the official platform is still on 2.x).",
        f"[env:{name}]",
        f"platform = {PIO_PLATFORM}",
        f"board = {chip['pio_board']}",
        "framework = arduino",
        "monitor_speed = 115200",
        "monitor_filters = esp32_exception_decoder",
        f"board_upload.flash_size = {board['flash_mb']}MB",
    ]
    partitions = {4: "default.csv", 8: "default_8MB.csv", 16: "default_16MB.csv"}.get(board["flash_mb"])
    if partitions:
        lines.append(f"board_build.partitions = {partitions}")
    if board["psram_mode"] != "none":
        lines.append("board_build.arduino.memory_type = "
                     + ("qio_opi" if board["psram_mode"] == "octal" else "qio_qspi"))
        flags.append("-DBOARD_HAS_PSRAM")
    if board["usb"].get("console") == "usb_serial_jtag":
        flags += ["-DARDUINO_USB_MODE=1", "-DARDUINO_USB_CDC_ON_BOOT=1"]
    lines.append("build_flags =")
    lines += [f"    {f}" for f in flags]
    return "\n".join(lines) + "\n"


def _fill(template: str, values: Dict[str, str]) -> str:
    for k, v in values.items():
        template = template.replace("{{" + k + "}}", v)
    return template


def _tmpl(rel: str) -> str:
    return (TEMPLATES_DIR / rel).read_text(encoding="utf-8")


def plan_project(board: Dict[str, Any], chip: Dict[str, Any], framework: str, name: str,
                 with_display: bool = False) -> Dict[str, str]:
    """Return {relative path: file content} for a new project.

    with_display adds LCD/touch/LVGL code (ESP-IDF only). Raises UnsupportedDisplay
    when the board's display data isn't complete enough to generate it.
    """
    if framework not in FRAMEWORKS:
        raise ValueError(f"framework must be one of {FRAMEWORKS}")
    if with_display and framework != "idf":
        raise ValueError("--with display is only available for --framework idf for now")
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_\-]*", name):
        raise ValueError("project name must start with a letter and use letters, digits, '_' or '-'")
    values = {
        "NAME": name,
        "BOARD_NAME": board["name"],
        "BOARD_ID": board["id"],
        "TARGET": chip["idf_target"],
        "FQBN": arduino_fqbn(board, chip),
        "SOURCE": (board["verification"].get("sources") or [""])[0],
        "STATUS": board["verification"]["status"],
        "DISPLAY_INCLUDE": '#include "display.h"\n#define APP_HAS_DISPLAY 1\n' if with_display else "",
        "SRCS": '"main.c" "display.c"' if with_display else '"main.c"',
    }
    header = render_header(board)
    files: Dict[str, str] = {".gitignore": _tmpl("common/gitignore.tmpl")}
    if framework == "idf":
        files.update({
            "CMakeLists.txt": _fill(_tmpl("idf/CMakeLists.txt.tmpl"), values),
            "main/CMakeLists.txt": _fill(_tmpl("idf/main_CMakeLists.txt.tmpl"), values),
            "main/main.c": _fill(_tmpl("idf/main.c.tmpl"), values),
            "main/idf_component.yml": idf_component_yml(
                board, display_dependencies(board) if with_display else None),
            "main/board_pins.h": header,
            "sdkconfig.defaults": sdkconfig_defaults(board, chip),
            "README.md": _fill(_tmpl("idf/README.md.tmpl"), values),
        })
        if with_display:
            files.update(render_display(board, _tmpl("idf/display.c.tmpl")))
    elif framework == "arduino":
        files.update({
            f"{name}.ino": _fill(_tmpl("arduino/app.cpp.tmpl"), values),
            "board_pins.h": header,
            "sketch.yaml": f"default_fqbn: {values['FQBN']}\n",
            "README.md": _fill(_tmpl("arduino/README.md.tmpl"), values),
        })
        # Arduino requires the sketch folder name to match the .ino name.
        files = {f"{name}/{k}": v for k, v in files.items()}
    else:
        files.update({
            "platformio.ini": platformio_ini(board, chip, name),
            "src/main.cpp": _fill(_tmpl("arduino/app.cpp.tmpl"), values),
            "include/board_pins.h": header,
            "README.md": _fill(_tmpl("pio/README.md.tmpl"), values),
        })
    return files


def write_project(files: Dict[str, str], out_dir: Path, force: bool = False) -> List[Path]:
    out_dir = Path(out_dir)
    existing = [out_dir / rel for rel in files if (out_dir / rel).exists()]
    if existing and not force:
        raise FileExistsError("Refusing to overwrite: " + ", ".join(str(p) for p in existing))
    written = []
    for rel, content in files.items():
        path = out_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:  # Path.write_text(newline=) needs 3.10
            f.write(content)
        written.append(path)
    return written
